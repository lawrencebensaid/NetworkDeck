#!/usr/bin/env python3
"""Render Inter (SIL OFL 1.1) into the anti-aliased glyph atlas used by deck_ui.

    python fontgen.py <Inter-SemiBold.ttf> > ../../firmware/components/deck_ui/src/font_data.cpp
    python fontgen.py --mono <PTMono.ttc> > ../../firmware/components/deck_ui/src/font_mono_data.cpp

The second form renders PT Mono (ParaType Free Font License), the typewriter face of the dock's info keys, as
kMonoFont from the collection's Regular face. macOS ships it at
/System/Library/Fonts/Supplemental/PTMono.ttc.

Needs Pillow. ASCII 32..126 at three pixel sizes; 8-bit coverage per pixel.
"""
import sys

from PIL import Image, ImageDraw, ImageFont

SIZES = [("kSmall", 11), ("kMedium", 14), ("kLarge", 20)]
FIRST, LAST = 32, 126


def render(font_path, px, index=0):
    font = ImageFont.truetype(font_path, px, index=index)
    ascent, descent = font.getmetrics()
    glyphs, data = [], []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        left, top, right, bottom = font.getbbox(ch)
        adv = round(font.getlength(ch))
        w, h = max(0, right - left), max(0, bottom - top)
        offset = len(data)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255)
            data.extend(img.tobytes())
        glyphs.append((offset, w, h, left, top, adv))
    return ascent, descent, glyphs, data


def regular_index(path):
    """The Regular face of a font collection (PTMono.ttc holds Bold first)."""
    for i in range(8):
        try:
            if ImageFont.truetype(path, 12, index=i).getname()[1] == "Regular":
                return i
        except OSError:
            break
    return 0


MONO_SIZES = [("kMono", 13)]


def main():
    mono = sys.argv[1] == "--mono"
    path = sys.argv[2] if mono else sys.argv[1]
    sizes = MONO_SIZES if mono else SIZES
    face = ("PT Mono", "ParaType Free Font License", "PTMono-LICENSE.txt") if mono else ("Inter SemiBold", "SIL Open Font License 1.1", "Inter-LICENSE.txt")
    out = [
        f"// Generated by tools/fontgen/fontgen.py from {face[0]} ({face[1]},",
        f"// see third_party/{face[2]}). Do not edit.",
        '#include "deck_ui/font.hpp"',
        "",
        "namespace deck_ui {",
        "",
    ]
    for name, px in sizes:
        ascent, descent, glyphs, data = render(path, px, regular_index(path) if mono else 0)
        out.append(f"static const uint8_t {name}Bitmap[] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const Glyph {name}Glyphs[] = {{")
        for g in glyphs:
            out.append("    {%d, %d, %d, %d, %d, %d}," % g)
        out.append("};")
        out.append(f"const Font {name}Font = {{{ascent}, {descent}, {FIRST}, {LAST}, {name}Glyphs, {name}Bitmap}};")
        out.append("")
    out.append("}  // namespace deck_ui")
    print("\n".join(out))


if __name__ == "__main__":
    main()
