#!/usr/bin/env python3
"""Render Inter (SIL OFL 1.1) into the anti-aliased glyph atlas used by deck_ui.

    python fontgen.py <Inter-SemiBold.ttf> > ../../firmware/components/deck_ui/src/font_data.cpp

Needs Pillow. ASCII 32..126 at three pixel sizes; 8-bit coverage per pixel.
"""
import sys

from PIL import Image, ImageDraw, ImageFont

SIZES = [("kSmall", 11), ("kMedium", 14), ("kLarge", 20)]
FIRST, LAST = 32, 126


def render(font_path, px):
    font = ImageFont.truetype(font_path, px)
    ascent, descent = font.getmetrics()
    glyphs, data = [], []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        left, top, right, bottom = font.getbbox(ch)
        adv = round(font.getlength(ch))
        w, h = max(0, right - left), max(0, bottom - top)
        offset = len(data)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255)
            data.extend(img.tobytes())
        glyphs.append((offset, w, h, left, top, adv))
    return ascent, descent, glyphs, data


def main():
    path = sys.argv[1]
    out = [
        "// Generated by tools/fontgen/fontgen.py from Inter SemiBold (SIL Open Font License 1.1,",
        "// see third_party/Inter-LICENSE.txt). Do not edit.",
        '#include "deck_ui/font.hpp"',
        "",
        "namespace deck_ui {",
        "",
    ]
    for name, px in SIZES:
        ascent, descent, glyphs, data = render(path, px)
        out.append(f"static const uint8_t {name}Bitmap[] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const Glyph {name}Glyphs[] = {{")
        for g in glyphs:
            out.append("    {%d, %d, %d, %d, %d, %d}," % g)
        out.append("};")
        out.append(f"const Font {name}Font = {{{ascent}, {descent}, {FIRST}, {LAST}, {name}Glyphs, {name}Bitmap}};")
        out.append("")
    out.append("}  // namespace deck_ui")
    print("\n".join(out))


if __name__ == "__main__":
    main()
